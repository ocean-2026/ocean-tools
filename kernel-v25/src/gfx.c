/* Reload the 8x16 glyph set into VGA plane 2 (offset 0x4000).  Mode 13h
 * writes (chain-4) clobber the font plane, so restoring text mode requires
 * re-seeding the glyphs that the VGA text renderer reads from there.
 */
static void vga_reload_font(void) {
    /* QEMU's text-mode VGA window mapping is memory_map_mode 3
     * (GC 0x06 = 0x0E): only the 0xB8000 window (offset 0..0x7FFF)
     * reaches VRAM; writes to 0xA0000 are discarded (addr underflows).
     * With GC 0x05 = 0x00 (latched access) a byte at window offset a
     * lands in VRAM at 4*a + plane.  QEMU renders 8x16 glyphs from
     * plane 2 starting at vram[2 + 128*c + 4*r], so write glyph char c,
     * row r (8x16 = each 8x8 row doubled) with a = 32*c + r, plane 2. */
    volatile uint8_t *p = (volatile uint8_t *)0xB8000;
    outb(0x3CE, 0x05); outb(0x3CF, 0x00);   /* write mode 0 (latched) */
    outb(0x3CE, 0x06); outb(0x3CF, 0x0E);
    for (int c = 0; c < 256; c++) {
        const unsigned char *g = font8x8_basic[0];   /* default '?' */
        if (c >= 0x20 && c <= 0x7E) g = font8x8_basic[c - 0x20];
        for (int r = 0; r < 16; r++) {
            unsigned char row = g[r >> 1];
            outb(0x3C4, 0x02); outb(0x3C5, 0x04);   /* plane 2: 8px row */
            p[32 * c + r] = row;
        }
    }
    outb(0x3C4, 0x02); outb(0x3C5, 0x0F);   /* all planes */
    outb(0x3CE, 0x05); outb(0x3CF, 0x10);   /* restore odd/even text mode */
}

void gfx_drawchar(int x, int y, char ch, uint8_t fg, uint8_t bg) {
    if (ch < 0x20 || ch > 0x7E) ch = '?';
    const unsigned char *g = font8x8_basic[ch - 0x20];
    for (int j = 0; j < 8; j++) {
        unsigned char row = g[j];
        for (int i = 0; i < 8; i++)
            gfx_putpixel(x + i, y + j, (row & (1u << (7 - i))) ? fg : bg);
    }
}

void gfx_text(int x, int y, const char *s, uint8_t fg, uint8_t bg) {
    int cx = x;
    while (*s) {
        gfx_drawchar(cx, y, *s++, fg, bg);
        cx += 8;
        if (cx >= GFX_W - 8) break;
    }
}

/* ---- 40x25 graphics-mode soft terminal ---- */

static int term_x, term_y;
static uint8_t term_fg = 7, term_bg = 0;

void gfx_term_set_color(uint8_t fg, uint8_t bg) { term_fg = fg; term_bg = bg; }

void gfx_term_clear(void) {
    gfx_fillrect(0, 0, GFX_W, GFX_H, term_bg);
    term_x = 0; term_y = 0;
}

static void term_scroll(void) {
    /* move 200-8 rows up by 8 pixels */
    volatile uint8_t *src = fb + 8 * GFX_W;
    for (int y = 0; y < GFX_H - 8; y++)
        for (int x = 0; x < GFX_W; x++)
            fb[y * GFX_W + x] = src[y * GFX_W + x];
    gfx_fillrect(0, GFX_H - 8, GFX_W, 8, term_bg);
    term_y = GFX_ROWS - 1;
}

void gfx_term_putc(char c) {
    switch (c) {
    case '\n':
        term_x = 0; term_y++;
        break;
    case '\r':
        term_x = 0;
        break;
    case '\b':
        if (term_x > 0) term_x--;
        break;
    case '\t':
        term_x = (term_x + 4) & ~3;
        break;
    default:
        gfx_drawchar(term_x * 8, term_y * 8, c, term_fg, term_bg);
        term_x++;
        break;
    }
    if (term_x >= GFX_COLS) { term_x = 0; term_y++; }
    if (term_y >= GFX_ROWS) term_scroll();
}

void gfx_term_write(const char *s) {
    while (*s) gfx_term_putc(*s++);
}

void gfx_term_init(void) {
    term_x = 0; term_y = 0; term_fg = 7; term_bg = 0;
    gfx_term_clear();
}
