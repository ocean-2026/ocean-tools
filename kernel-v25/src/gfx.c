/* ---- DAC palette: 16 standard colours + 240 greys ---- */

void gfx_set_palette(void) {
    static const uint8_t v[16][3] = {
        {0,0,0},{0,0,170},{0,170,0},{0,170,170},
        {170,0,0},{170,0,170},{170,85,0},{170,170,170},
        {85,85,85},{85,85,255},{85,255,85},{85,255,255},
        {255,85,85},{255,85,255},{255,255,85},{255,255,255}
    };
    outb(0x3C8, 0x00);
    for (int i = 0; i < 16; i++) {
        outb(0x3C9, v[i][0]); outb(0x3C9, v[i][1]); outb(0x3C9, v[i][2]);
    }
    for (int i = 16; i < 256; i++) {
        uint8_t g = (uint8_t)((i - 16) * 255 / 239);
        outb(0x3C9, g); outb(0x3C9, g); outb(0x3C9, g);
    }
}

/* ---- framebuffer primitives ---- */

static volatile uint8_t *fb = (volatile uint8_t *)GFX_FB;

void gfx_putpixel(int x, int y, uint8_t c) {
    if (x < 0 || x >= GFX_W || y < 0 || y >= GFX_H) return;
    fb[y * GFX_W + x] = c;
}

void gfx_fillrect(int x, int y, int w, int h, uint8_t c) {
    for (int j = 0; j < h; j++)
        for (int i = 0; i < w; i++)
            gfx_putpixel(x + i, y + j, c);
}

void gfx_hline(int x, int y, int w, uint8_t c) {
    for (int i = 0; i < w; i++) gfx_putpixel(x + i, y, c);
}

void gfx_vline(int x, int y, int h, uint8_t c) {
    for (int j = 0; j < h; j++) gfx_putpixel(x, y + j, c);
}

void gfx_rect(int x, int y, int w, int h, uint8_t c) {
    gfx_hline(x, y, w, c);
    gfx_hline(x, y + h - 1, w, c);
    gfx_vline(x, y, h, c);
    gfx_vline(x + w - 1, y, h, c);
}

